/**
 * Write src/generated/contracts.ts from Foundry's build output: the ABI and
 * creation bytecode of each deployable contract, typed `as const` for viem.
 * Run after `pnpm build:contracts`; the file is committed so the TypeScript
 * packages typecheck without a Solidity toolchain.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const CONTRACTS = [
  "ParticipantRegistry",
  "WholesaleToken",
  "DepositToken",
  "SettlementEngine",
  "ConditionalSettlement",
  "ConfidentialSettlement",
  "Bond",
  // ERC-3643 for the bond (contracts/src/erc3643), this project's own implementation of the standard.
  "Identity",
  "ClaimIssuer",
  "ClaimTopicsRegistry",
  "TrustedIssuersRegistry",
  "IdentityRegistryStorage",
  "IdentityRegistry",
  "ModularCompliance",
  "SettlementOnlyModule",
  // OpenZeppelin's, built for confidential mode's Paladin NotoFactory (contracts/src/PaladinProxy.sol).
  "ERC1967Proxy",
  // The conformance kit's broken engines (contracts/src/broken), never deployed outside it.
  "NoOnceEngine",
  "LaxMintEngine",
  "SplitLegsEngine",
  "OpenDepositToken",
] as const;

const root = path.resolve(import.meta.dirname, "../../..");
const out = path.join(root, "contracts/out");
const target = path.resolve(import.meta.dirname, "../src/generated/contracts.ts");

const parts = [
  "// Generated by packages/chain/scripts/generate-contracts.ts from contracts/out.",
  "// Do not edit: run `pnpm build:contracts && pnpm --filter @oul/chain generate`.",
  "",
];
for (const name of CONTRACTS) {
  const artifact = JSON.parse(await readFile(path.join(out, `${name}.sol`, `${name}.json`), "utf8")) as {
    abi: unknown[];
    bytecode: { object: string };
  };
  parts.push(
    `export const ${name} = {`,
    `  abi: ${JSON.stringify(artifact.abi)},`,
    `  bytecode: ${JSON.stringify(artifact.bytecode.object)},`,
    "} as const;",
    "",
  );
}
await writeFile(target, parts.join("\n"));
console.log(`Wrote ${path.relative(root, target)} (${CONTRACTS.join(", ")})`);
